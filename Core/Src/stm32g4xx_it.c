/**
  * @brief This function handles UART4 global interrupt / UART4 wake-up interrupt through EXTI line 34.
  */
void UART4_IRQHandler(void)
{
  /* USER CODE BEGIN UART4_IRQn 0 */
	// 오버런/프레이밍 에러 플래그가 남아 수신이 멈추는 것을 방지
	if (LL_USART_IsActiveFlag_ORE(UART4)) {
		LL_USART_ClearFlag_ORE(UART4);
	}
	if (LL_USART_IsActiveFlag_RXNE(UART4) && LL_USART_IsEnabledIT_RXNE(UART4)) {
		uint8_t b = LL_USART_ReceiveData8(UART4);
		if (uart4_rx_previous == 0x20 && b == 0x40) {
			// iBus 헤더(0x20 0x40): 데이터 시작. previous 를 비워 다음 데이터 바이트와의 오검출 방지
			uart4_rx_cnt = 0;
			uart4_rx_previous = 0;
		} else {
			if (uart4_rx_cnt < sizeof(uart4_rx_data)) { // 범위 초과 쓰기 방지
				uart4_rx_data[uart4_rx_cnt++] = b;
			}
			uart4_rx_previous = b;
		}
	}
	/*
	 Check if the USART IDLE line detected Flag is set or not.
	 The FS-I6's data packet with IBus protocol has the IDLE time of about 8ms!
	 */
	if (LL_USART_IsActiveFlag_IDLE(UART4)) {
		LL_USART_ClearFlag_IDLE(UART4);
		uart4_rx_idle = true;
		uart4_rx_cnt = 0;
	}
  /* USER CODE END UART4_IRQn 0 */
  /* USER CODE BEGIN UART4_IRQn 1 */

  /* USER CODE END UART4_IRQn 1 */
}

